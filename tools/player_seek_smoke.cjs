const assert=require('node:assert/strict');
const {chromium}=require('../logs/web_browser_qa/node_modules/playwright');
(async()=>{
  const base=process.argv[2]||'http://127.0.0.1:8080';
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  const page=await browser.newPage();const errors=[];let streams=0;
  page.on('request',request=>{if(request.url().includes('/api/stream/'))streams++;});
  page.on('pageerror',error=>errors.push(error.message));
  try{
    await page.goto(base);
    await page.waitForFunction(()=>document.getElementById('connection').textContent==='服务已连接');
    assert.equal(await page.locator('#play-progress').isDisabled(),true);
    await page.locator('#show-previous-tasks').check();
    await page.waitForSelector('#jobs .job');await page.locator('#jobs .job').first().click();
    await page.waitForFunction(()=>document.getElementById('preview').naturalWidth>0&&player.position>0.5,{},{timeout:60000});
    const available=await page.evaluate(()=>player.available);
    assert.ok(available>1);
    assert.equal(await page.locator('#show-history').count(),0);
    await page.locator('#play-toggle').click();
    const stopped=await page.evaluate(()=>player.position);
    await page.waitForTimeout(350);
    assert.equal(await page.evaluate(()=>player.position),stopped);
    await page.evaluate(()=>{const input=document.getElementById('play-progress');input.value=String(Math.min(2,player.available/2));input.dispatchEvent(new Event('input'));input.dispatchEvent(new Event('change'));});
    await page.waitForFunction(()=>player.renderedPosition>=1.8,{},{timeout:10000});
    await page.evaluate(()=>{const input=document.getElementById('play-progress');input.value='0.2';input.dispatchEvent(new Event('input'));input.dispatchEvent(new Event('change'));});
    await page.waitForFunction(()=>player.renderedPosition<0.3,{},{timeout:10000});
    await page.waitForTimeout(300);
    assert.ok(await page.evaluate(()=>player.position<0.3));
    const beforeResume=streams;
    await page.locator('#play-toggle').click();
    await page.waitForFunction(()=>player.position>0.6);
    assert.equal(streams,beforeResume,'resume restarted the stream');
    await page.locator('#play-toggle').click();
    const target=available-0.5;
    const seekStarted=Date.now();
    await page.evaluate(target=>{const input=document.getElementById('play-progress');input.value=String(target);input.dispatchEvent(new Event('input'));input.dispatchEvent(new Event('change'));},target);
    await page.waitForFunction(target=>Math.abs(player.renderedPosition-target)<0.12,target,{timeout:5000});
    const seekLatency=Date.now()-seekStarted;
    assert.ok(seekLatency<1500,`far seek took ${seekLatency} ms`);
    const request=await page.evaluate(()=>({device:state.device,job:state.selected,available:player.available}));
    const invalid=await page.request.get(`${base}/api/stream/${request.device}?job_id=${request.job}&offset=${request.available+1}`);
    assert.equal(invalid.status(),416);
    assert.ok(Number(await page.locator('#play-progress').getAttribute('max'))<available);
    await page.locator('.segment').first().click();
    await page.waitForFunction(()=>player.available>0&&player.available<=1.1);
    await page.reload();
    await page.waitForFunction(()=>document.getElementById('connection').textContent==='服务已连接');
    assert.equal(await page.locator('#preview').getAttribute('src'),null);
    assert.equal(await page.locator('#play-progress').isDisabled(),true);
    assert.deepEqual(errors,[]);
    console.log(`PASS: far seek ${seekLatency} ms, resume reuses connection, backwards and paused seeks, unavailable seek rejected, segment replay and fresh reload`);
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
